/** A single brand glyph, sized via CSS (`.cc-logo`). */
export function IntegrationGlyph({ brand, className }: { brand: BrandKey; className?: string }) {
  return <span className={`cc-logo${className ? ` ${className}` : ""}`}>{BRANDS[brand].glyph}</span>;
}

/** Glyph + label pill, used inside feature sections. */
export function IntegrationChip({ brand }: { brand: BrandKey }) {
  const b = BRANDS[brand];
  return (
    <span className="cc-chip" data-category={b.category}>
      <IntegrationGlyph brand={brand} />
      {b.label}
    </span>
  );
}
